-- Q630: Customer Revenue Rank Within City
-- ============================================================
-- Task:
-- Rank customers by revenue within their city.
--
-- If two customers have the same revenue,
-- they receive the same rank.
--
-- Concepts:
-- DENSE_RANK()
-- PARTITION BY
-- City-Level Ranking
-- Customer Analytics
-- ============================================================

WITH customer_revenue AS (

    SELECT
        c.customer_id,
        c.customer_name,
        c.city,

        SUM(
            oi.quantity * oi.price
        ) AS revenue

    FROM customers c

    JOIN orders o
        ON c.customer_id = o.customer_id

    JOIN order_items oi
        ON o.order_id = oi.order_id

    GROUP BY
        c.customer_id,
        c.customer_name,
        c.city
),

ranked_customers AS (

    SELECT
        customer_id,
        customer_name,
        city,
        revenue,

        DENSE_RANK() OVER (
            PARTITION BY city
            ORDER BY revenue DESC
        ) AS city_revenue_rank

    FROM customer_revenue
)

SELECT
    customer_id,
    customer_name,
    city,
    revenue,
    city_revenue_rank

FROM ranked_customers

ORDER BY
    city,
    city_revenue_rank;


